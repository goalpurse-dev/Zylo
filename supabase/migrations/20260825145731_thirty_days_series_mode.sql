-- Persistent, progressively billed 30 Days Series mode. Single-video rows
-- remain unchanged. A series owns one setup generation (persistent visual
-- references) and each episode owns a normal reservation-backed generation,
-- so the existing jobs/asset authorization/refund machinery is reused.

CREATE TABLE public.thirty_days_series (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  title text NOT NULL,
  universe text NOT NULL,
  premise text NOT NULL,
  visual_style text NOT NULL DEFAULT 'auto'
    CHECK (visual_style IN ('auto', 'cinematic_3d', 'anime_accurate', 'realistic', 'dark_cinematic')),
  quality_tier text NOT NULL REFERENCES public.thirty_days_quality_tiers(quality_tier),
  days_per_episode integer NOT NULL DEFAULT 1 CHECK (days_per_episode IN (1, 2, 3, 5)),
  total_days integer NOT NULL DEFAULT 30 CHECK (total_days > 0),
  current_day integer NOT NULL DEFAULT 0 CHECK (current_day >= 0),
  current_episode integer NOT NULL DEFAULT 0 CHECK (current_episode >= 0),
  status text NOT NULL DEFAULT 'planning'
    CHECK (status IN ('planning', 'references', 'ready', 'generating', 'completed', 'failed')),
  master_story_bible jsonb NOT NULL DEFAULT '{}'::jsonb,
  hidden_future_beats jsonb NOT NULL DEFAULT '[]'::jsonb,
  reference_library jsonb NOT NULL DEFAULT '[]'::jsonb,
  current_story_state jsonb NOT NULL DEFAULT '{}'::jsonb,
  next_episode_tease text,
  cover_url text,
  setup_generation_id uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  last_active_at timestamptz NOT NULL DEFAULT now(),
  CHECK (current_day <= total_days),
  CHECK (jsonb_typeof(master_story_bible) = 'object'),
  CHECK (jsonb_typeof(hidden_future_beats) = 'array'),
  CHECK (jsonb_typeof(reference_library) = 'array'),
  CHECK (jsonb_array_length(reference_library) <= 10),
  CHECK (jsonb_typeof(current_story_state) = 'object')
);

CREATE TABLE public.thirty_days_series_episodes (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  series_id uuid NOT NULL REFERENCES public.thirty_days_series(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  generation_id uuid,
  episode_number integer NOT NULL CHECK (episode_number > 0),
  start_day integer NOT NULL CHECK (start_day > 0),
  end_day integer NOT NULL CHECK (end_day >= start_day),
  title text NOT NULL,
  hook text NOT NULL,
  story_plan jsonb NOT NULL DEFAULT '{}'::jsonb,
  episode_summary jsonb NOT NULL DEFAULT '{}'::jsonb,
  cliffhanger text,
  next_episode_tease text,
  narration text,
  narration_take jsonb,
  thumbnail_url text,
  final_video_url text,
  status text NOT NULL DEFAULT 'generating'
    CHECK (status IN ('planning', 'generating', 'voiceover', 'stitching', 'completed', 'partial', 'failed')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz,
  UNIQUE (series_id, episode_number),
  UNIQUE (series_id, start_day, end_day),
  CHECK (jsonb_typeof(story_plan) = 'object'),
  CHECK (jsonb_typeof(episode_summary) = 'object')
);

