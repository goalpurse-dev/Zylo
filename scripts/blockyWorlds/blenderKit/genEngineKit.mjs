// WHAT THE ENGINE CAN SHOW, GENERATED FROM THE CODE (owner 2026-11-23, round 7): the writer and the plan may only use
// these, so the list is read from the engine itself, never typed by hand:
//   things   = every kind a prop builder has (acts.py zt_build + the overrides in crowds / town / effects)
//   actions  = every action the card compiler turns into engine code (cards.mjs compileScene's cases + gestures)
//   places   = the world library's places (worlds.py ZW_PLACES)
//   effects  = what can happen to things (the compiler + the rule effect + switches)
//   recipes  = the named shot recipes (establishing moves, the window look-out, the porch)
// Writes supabase/functions/_shared/blockyWorlds/engineKitGenerated.js. Free, local; run after any engine change:
//   node scripts/blockyWorlds/blenderKit/genEngineKit.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const W = (f) => fs.readFileSync(path.join(HERE, "worlds", f), "utf8");
const acts = W("acts.py"), worlds = W("worlds.py");
const extra = ["crowds.py", "town.py", "effects.py"].map(W).join("\n");

// things: the kinds with their own build branch
const zt = acts.slice(acts.indexOf("def zt_build("), acts.indexOf("def zw_thing("));
const things = new Set();
for (const m of zt.matchAll(/\bk == "([a-z_]+)"/g)) things.add(m[1]);
for (const m of zt.matchAll(/\bk in \(([^)]*)\)/g)) for (const q of m[1].matchAll(/"([a-z_]+)"/g)) things.add(q[1]);
// (only inside the overriding zt_build functions: switch targets like a lamp or a window are not props)
const ztOver = [...extra.matchAll(/def zt_build\(kind, r, c, col\):([\s\S]*?)\n(?=def |ZW_|# )/g)].map((m) => m[1]).join("\n");
for (const m of ztOver.matchAll(/\bkind == "([a-z_]+)"/g)) things.add(m[1]);
for (const m of ztOver.matchAll(/kind in \(([^)]*)\)/g)) for (const q of m[1].matchAll(/"([a-z_]+)"/g)) things.add(q[1]);

// actions: the compiler's scene-card cases
const cards = fs.readFileSync(path.join(HERE, "cards.mjs"), "utf8");
const cs = cards.slice(cards.indexOf("export function compileScene("));
const actions = new Set(["stand"]);
for (const m of cs.matchAll(/case "([a-z_]+)":/g)) actions.add(m[1]);
for (const m of cards.matchAll(/const GESTURES = \{([^}]*)\}/g)) for (const q of m[1].matchAll(/([a-z_]+):/g)) actions.add(q[1]);

// places
const pl = worlds.slice(worlds.indexOf("ZW_PLACES = {"), worlds.indexOf("}", worlds.indexOf("ZW_PLACES = {")));
const places = [...pl.matchAll(/"([a-z_]+)":/g)].map((m) => m[1]);

const effects = ["pop", "grow", "shrink", "rain", "rule_effect", "switch"];
const recipes = ["street_glide", "low_drone", "follow_walk", "window_lookout", "porch", "wide", "medium", "two", "close", "insert", "low", "high", "monster_reveal", "monster_full"];

const out = `// GENERATED by scripts/blockyWorlds/blenderKit/genEngineKit.mjs from the engine's code (${new Date().toISOString().slice(0, 10)}). Do not edit.
export const GEN_THINGS = Object.freeze(${JSON.stringify([...things].sort())});
export const GEN_ACTIONS = Object.freeze(${JSON.stringify([...actions].sort())});
export const GEN_PLACES = Object.freeze(${JSON.stringify(places)});
export const GEN_EFFECTS = Object.freeze(${JSON.stringify(effects)});
export const GEN_RECIPES = Object.freeze(${JSON.stringify(recipes)});
`;
const dst = path.join(HERE, "..", "..", "..", "supabase", "functions", "_shared", "blockyWorlds", "engineKitGenerated.js");
fs.writeFileSync(dst, out);
console.log(`engine kit: ${things.size} things, ${actions.size} actions, ${places.length} places, ${effects.length} effects, ${recipes.length} recipes -> ${path.relative(process.cwd(), dst)}`);
