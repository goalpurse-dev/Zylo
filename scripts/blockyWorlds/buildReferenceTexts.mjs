// Blocky Worlds: writes supabase/functions/_shared/blockyWorlds/referenceTexts.js, the reference transcripts the hybrid
// writer uses as examples (broad.js RECIPE_REFERENCES), as plain narration text. The edge function can't read
// reference/blocky-worlds/analysis/ (only files under supabase/functions are bundled), so the texts are copied into a
// module. Free, no network. Run again after RECIPE_REFERENCES changes:  node scripts/blockyWorlds/buildReferenceTexts.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { RECIPE_REFERENCES, transcriptText } from "../../supabase/functions/_shared/blockyWorlds/broad.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const ids = [...new Set(Object.values(RECIPE_REFERENCES).flat())].sort();
const texts = Object.fromEntries(ids.map((id) => [id, transcriptText(JSON.parse(readFileSync(path.join(root, "reference/blocky-worlds/analysis", id, "transcript.json"), "utf8")))]));
for (const [id, t] of Object.entries(texts)) if (!t) throw new Error(`reference ${id} has no text`);

const out = `// GENERATED by scripts/blockyWorlds/buildReferenceTexts.mjs from reference/blocky-worlds/analysis/<id>/transcript.json.
// Do not edit by hand. The reference transcripts (broad.js RECIPE_REFERENCES) as plain narration text, so the edge
// function can put them into the hybrid writer's cached examples block.
import { RECIPE_REFERENCES } from "./broad.js";

export const REFERENCE_TEXTS = Object.freeze(${JSON.stringify(texts, null, 2)});

/** The examples for ids, in the given order: [{ id, text, firstLine }]; unknown ids are skipped. */
export function examplesByIds(ids) {
  return (ids ?? []).filter((id) => REFERENCE_TEXTS[id]).map((id) => ({ id, text: REFERENCE_TEXTS[id], firstLine: REFERENCE_TEXTS[id].split(/(?<=[.!?])\\s+/)[0] }));
}

/** The examples a recipe learns from (best first). The same recipe always gives the same list: a stable cached prefix. */
export const examplesFor = (recipeId) => examplesByIds(RECIPE_REFERENCES[recipeId] ?? []);
`;
writeFileSync(path.join(root, "supabase/functions/_shared/blockyWorlds/referenceTexts.js"), out);
console.log(`wrote ${ids.length} references, ${out.length} characters`);
